  const languages = window.ColorAtlasConfig.languages;
  const supported = languages.map(language => language.id);
  const storageKey = 'coloratlas_language';
  const fromQuery = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try { saved = localStorage.getItem(storageKey); } catch {}
  const browser = navigator.language || window.ColorAtlasConfig.defaultLanguage;
  const inferred = browser.toLowerCase().startsWith('zh-cn') || browser.toLowerCase().startsWith('zh-sg') ? 'zh-Hans' : browser.toLowerCase().startsWith('en') ? 'en' : window.ColorAtlasConfig.defaultLanguage;
  let locale = supported.includes(fromQuery) ? fromQuery : supported.includes(saved) ? saved : inferred;
  const translate = (language, key) => dictionaries[language]?.[key] ?? dictionaries[window.ColorAtlasConfig.defaultLanguage][key] ?? key;
  const t = (key, params = {}) => {
    const template = translate(locale, key);
    params = { min: window.ColorAtlasConfig.fidelity.min, max: window.ColorAtlasConfig.fidelity.max, ...params };
    return String(template).replace(/\{([a-zA-Z]+)\}/g, (_, token) => params[token] ?? `{${token}}`);
  };
  const apply = () => {
    document.documentElement.lang = locale;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    for (const attribute of ['placeholder', 'title', 'aria-label', 'alt', 'content']) {
      document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`))));
    }
    const select = document.getElementById('languageSelect');
    if (select) select.value = locale;
    document.title = t('meta.title');
  };
  const setLanguage = next => {
    if (!supported.includes(next) || next === locale) return;
    locale = next;
    try { localStorage.setItem(storageKey, locale); } catch {}
    apply();
    document.dispatchEvent(new CustomEvent('coloratlas:languagechange', { detail: { locale } }));
  };
  const initialize = () => {
    apply();
    const select = document.getElementById('languageSelect');
    if (select) {
      select.replaceChildren(...languages.map(language => {
        const option = document.createElement('option');
        option.value = language.id;
        option.textContent = language.label;
        return option;
      }));
      select.value = locale;
      select.addEventListener('change', event => setLanguage(event.target.value));
    }
  };
  window.ColorAtlasI18n = Object.freeze({ t, translate, setLanguage, get locale() { return locale; }, supported });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initialize);
